/**
 * whatsapp-link.ts
 * ---------------------------------------------------------------------------
 * الجزء الصالح للمتصفح من تكامل واتساب: نص الرسالة ورابط wa.me.
 *
 * مفصول عن whatsapp.ts لأن ذاك الملف server-only (يحمل المفاتيح)، وهذا يُستورد
 * في مكوّنات العميل. النص واحد في الحالتين فلا تختلف الرسالة بين الوضع اليدوي
 * والتلقائي.
 *
 * النص مطابق لنص الدعوة المعتمد في التصميم الرسمي.
 */

/** نص الرسالة المرافقة للدعوة. */
export function invitationCaption(guestName: string): string {
  return [
    'دعوة حضور — الأسبوع العلمي السابع',
    '',
    `الفاضل/ة ${guestName}`,
    '',
    'يسر الكلية العسكرية التقنية دعوتكم لحضور فعاليات الأسبوع العلمي السابع، ' +
      'الذي يجمع الباحثين والمبتكرين والخبراء لاستعراض أحدث الابتكارات والتقنيات ' +
      'المتقدمة وبناء شراكات استراتيجية تدعم المعرفة والبحث العلمي والاقتصاد المعرفي.',
    '',
    '📅 4 - 8 أكتوبر 2026م',
    '📍 الكلية العسكرية التقنية — مسقط',
    '',
    'نأمل تشريفكم بالحضور.',
  ].join('\n');
}

/** رابط المحادثة اليدوية مع رسالة جاهزة. لا يُرفق صورة — الإرفاق يدوي. */
export function waMeLink(toE164: string, guestName: string): string {
  const number = toE164.replace(/\D/g, '');
  return `https://wa.me/${number}?text=${encodeURIComponent(invitationCaption(guestName))}`;
}
